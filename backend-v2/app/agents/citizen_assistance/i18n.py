def _norm(text: str) -> str:
    return unicodedata.normalize("NFC", text).casefold()


class LocalizedRetriever:
    def __init__(self, corpus: dict[str, list[dict]] | None = None):
        self._corpus = corpus or CORPUS_I18N

    def retrieve(self, query: str, language: str, k: int = 2) -> list[dict]:
        q = _norm(query)
        scored = []
        for doc in self._corpus.get(language, []):
            hits = sum(1 for kw in doc["keywords"] if _norm(kw) in q)
            if hits:
                scored.append((hits, doc))
        scored.sort(key=lambda pair: pair[0], reverse=True)
        return [doc for _, doc in scored[:k]]
